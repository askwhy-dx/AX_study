# ---------- 소재 2 : 60건 · 서로 얽히지 않음 ----------
def s2():
    rnd = random.Random(7); out = HERE / "소재2"; out.mkdir(exist_ok=True)
    shutil.copy(BASE_RULE, out / "응대규정.md")
    names = "가나다라마바사아자차카타파하"
    items, key = [], {}
    kinds = ["보강", "교재", "반변경", "수강료", "휴원"] * 12
    rnd.shuffle(kinds)
    for i, k in enumerate(kinds, 1):
        who = f"학부모 {names[i % 14]}{i:02d}"
        if k == "보강":
            used, early = rnd.choice([0, 1, 2]), rnd.choice([True, False])
            q = (f"이번 달에 보강을 {used}번 받았어요. " + ("다음 주 화요일에 빠지는데 오늘 미리 말씀드려요." if early else "오늘 아침 아이가 아파서 오늘 수업에 못 가요.") + " 보강 잡아 주실 수 있나요?")
            a = "가능" if used < 2 and early else "불가"
        elif k == "교재":
            d, opened = rnd.choice([2, 4, 10, 12]), rnd.choice([True, False])
            q = f"{d}일 전에 교재를 받았는데 포장을 {'뜯었어요' if opened else '안 뜯었어요'}. 그만두게 됐는데 교재비 돌려받을 수 있나요?"
            a = "환불" if d < 7 and not opened else "불가"
        elif k == "반변경":
            d = rnd.choice([18, 24, 27, 29])
            q = f"이번 달 {d}일에 반 변경을 신청하려고 해요. 다음 달 1일부터 바뀌나요?"
            a = "다음달" if d <= 25 else "다다음달"
        elif k == "수강료":
            p = rnd.choice(["수업이 아직 시작 전", "한 달 수업의 4분의 1 정도 지난", "한 달 수업의 5분의 2 정도 지난", "한 달 수업의 3분의 2 정도 지난"])
            q = f"이번 달은 {p} 상태인데, 지금 그만두면 이번 달 수강료를 얼마나 돌려받나요?"
            a = {"수업이 아직 시작 전": "전액", "한 달 수업의 4분의 1 정도 지난": "3분의2", "한 달 수업의 5분의 2 정도 지난": "2분의1", "한 달 수업의 3분의 2 정도 지난": "없음"}[p]
        else:
            m, d = rnd.choice([1, 2, 3]), rnd.choice([10, 3])
            q = f"{d}일 뒤부터 {m}개월 휴원하려고 해요. 오늘 신청하면 되나요?"
            a = "가능" if m <= 2 and d >= 7 else "불가"
        items.append(f"[문의 {i}] {who}\n{q}\n"); key[i] = a
    (out / "문의.txt").write_text("가상 학부모 문의 60건 (교육용 · 지어낸 문의)\n받은 날: 모두 2026년 11월 22일\n\n" + "\n".join(items), encoding="utf-8")
    (out / "정답.json").write_text(json.dumps(key, ensure_ascii=False, indent=1), encoding="utf-8")
    (out / "결론낱말.txt").write_text(FMT + "\n결론 낱말: 가능 · 불가 · 환불 · 다음달 · 다다음달 · 전액 · 3분의2 · 2분의1 · 없음 · 확인\n", encoding="utf-8")

